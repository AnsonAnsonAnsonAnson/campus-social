#!/usr/bin/env bash
# Writes supabase/setup.sql: every migration in order, in one transaction, so a
# new Supabase project can be set up by pasting a single file into the SQL
# Editor. Run after adding a migration; test-db.sh fails if it is out of date.
#
#   bash scripts/make-setup-sql.sh            # rewrite supabase/setup.sql
#   bash scripts/make-setup-sql.sh --stdout   # print it instead
set -euo pipefail
cd "$(dirname "$0")/.."

generate() {
  echo "-- Campus Social database setup. Generated by scripts/make-setup-sql.sh; do not edit."
  echo "--"
  echo "-- For a NEW, empty Supabase project: open SQL Editor, paste this whole file,"
  echo "-- press Run. Everything runs in one transaction, so if anything fails nothing"
  echo "-- is changed. Projects that already ran it only need the newer files in"
  echo "-- supabase/migrations/ (or 'supabase db push')."
  echo
  echo "begin;"
  for f in supabase/migrations/*.sql; do
    echo
    echo "-- ===== $(basename "$f") ====="
    echo
    cat "$f"
  done
  echo
  echo "commit;"
}

if [[ "${1:-}" == "--stdout" ]]; then
  generate
else
  generate > supabase/setup.sql
  echo "Wrote supabase/setup.sql"
fi

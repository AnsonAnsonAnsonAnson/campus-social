// Generates supabase/seed.sql from src/lib/demoData.ts so demo mode and a fresh
// Supabase project show the same sample content.
// Run: node scripts/make-seed.ts   (Node 22.18+ runs TypeScript directly)
import { writeFileSync } from 'node:fs';

import { demoSocieties, hkAt, makeDemoBanners, makeDemoCampusDates, makeDemoEvents } from '../src/lib/demoData.ts';

const now = new Date();
const midnight = new Date(hkAt(0, 0, 0, now)).getTime();

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
// Timestamps become "HK midnight today + N minutes" so the seed never goes stale.
const ts = (iso: string | null) =>
  iso === null ? 'null' : `(pg_temp.hk_today() + interval '${Math.round((new Date(iso).getTime() - midnight) / 60000)} minutes')`;
const day = (d: string) => `(pg_temp.hk_today()::date + ${Math.round((new Date(`${d}T00:00:00+08:00`).getTime() - midnight) / 86400000)})`;

const out: string[] = [
  '-- Generated by scripts/make-seed.ts. Sample data only: edit src/lib/demoData.ts and re-run.',
  "create or replace function pg_temp.hk_today() returns timestamptz language sql as $$ select date_trunc('day', now() at time zone 'Asia/Hong_Kong') at time zone 'Asia/Hong_Kong' $$;",
];

for (const s of demoSocieties) {
  out.push(
    `insert into public.societies (id, name, short_name, description, category, college, instagram, status, verified, follower_count) values (${[
      s.id,
      s.name,
      s.short_name,
      s.description,
      s.category,
      s.college,
      s.instagram,
      s.status,
    ]
      .map(q)
      .join(', ')}, ${s.verified}, ${s.follower_count}) on conflict (id) do nothing;`,
  );
}
for (const e of makeDemoEvents(now)) {
  out.push(
    `insert into public.events (id, society_id, title, description, category, location, starts_at, ends_at, status, registration_required, capacity, waitlist_enabled, registration_opens_at, price_text, signup_question, members_only, price_hkd, member_price_hkd, payment_window_hours, featured_at) values (${[
      q(e.id),
      q(e.society_id),
      q(e.title),
      q(e.description),
      q(e.category),
      q(e.location),
      ts(e.starts_at),
      ts(e.ends_at),
      q(e.status),
      q(e.registration_required),
      q(e.capacity),
      q(e.waitlist_enabled),
      ts(e.registration_opens_at),
      q(e.price_text),
      q(e.signup_question),
      q(e.members_only),
      q(e.price_hkd),
      q(e.member_price_hkd),
      q(e.payment_window_hours),
      ts(e.featured_at),
    ].join(', ')}) on conflict (id) do nothing;`,
  );
}
for (const b of makeDemoBanners(now)) {
  out.push(
    `insert into public.banners (id, society_id, event_id, title, subtitle, starts_at, ends_at, priority, status) values (${[
      q(b.id),
      q(b.society_id),
      q(b.event_id),
      q(b.title),
      q(b.subtitle),
      ts(b.starts_at),
      ts(b.ends_at),
      q(b.priority),
      q(b.status),
    ].join(', ')}) on conflict (id) do nothing;`,
  );
}
for (const d of makeDemoCampusDates(now)) {
  out.push(
    `insert into public.campus_dates (id, title, title_zh, kind, college, starts_on, ends_on) values (${[
      q(d.id),
      q(d.title),
      q(d.title_zh ?? null),
      q(d.kind),
      q(d.college),
      day(d.starts_on),
      day(d.ends_on),
    ].join(', ')}) on conflict (id) do nothing;`,
  );
}
out.push('');

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'));
console.log('Wrote supabase/seed.sql');
